-- Run this in Supabase Dashboard -> SQL Editor.
create table if not exists public.providers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  location text not null,
  category text not null,
  specialties text default '',
  capacity text default '',
  price text default '',
  description text default '',
  consent boolean not null default false,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);
create index if not exists providers_location_status_idx on public.providers(location, status);
create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references public.providers(id),
  customer_name text not null,
  phone text not null,
  location text not null,
  event_type text not null,
  event_date text default '',
  guests text default '',
  budget text default '',
  notes text default '',
  created_at timestamptz not null default now()
);
-- Keep tables inaccessible through the public anon key. The Streamlit server uses
-- the Supabase service-role key stored privately in Streamlit Secrets.
alter table public.providers enable row level security;
alter table public.enquiries enable row level security;
revoke all on public.providers from anon, authenticated;
revoke all on public.enquiries from anon, authenticated;
